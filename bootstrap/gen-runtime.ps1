# Generate src/flintc/runtime.fl from src/runtime/runtime.asm.
# The runtime is assembled by the in-repo assembler; its bytes are embedded
# into the compiler as a Flint function so the compiler emits its own runtime.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$asm = Join-Path $PSScriptRoot 'asm.ps1'
$src = Join-Path $root 'src\runtime\runtime.asm'
$bin = Join-Path $root 'build\runtime.bin'
$map = Join-Path $root 'build\runtime.map.json'
$out = Join-Path $root 'src\flintc\runtime.fl'

New-Item -ItemType Directory -Force -Path (Split-Path -Parent $bin) | Out-Null
& pwsh -NoProfile -File $asm -Source $src -Output $bin -MapFile $map
if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $bin)) { throw "runtime assembly failed ($LASTEXITCODE)" }

$bytes = [IO.File]::ReadAllBytes($bin)
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// generated by bootstrap/gen-runtime.ps1 - do not edit')
$lines.Add('fn emit_runtime(c: ^Ctx) {')
foreach ($b in $bytes) { $lines.Add("    eb(c, $b);") }
$lines.Add('}')
[IO.File]::WriteAllLines($out, $lines, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("[runtime] {0} bytes -> {1}" -f $bytes.Length, $out)
